package com.backend.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.util.List;
import java.util.Date;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import com.backend.entity.IndividualEntity;
import com.backend.entity.MorphMasterEntity;
import com.backend.mapper.BloodlineMasterMapper;
import com.backend.mapper.IndividualBloodlineMapper;
import com.backend.mapper.IndividualMapper;
import com.backend.mapper.IndividualMorphMapper;
import com.backend.mapper.MorphMasterMapper;
import com.backend.mapper.PairingMapper;
import com.backend.model.Individual;
import com.backend.model.IndividualMorph;

@ExtendWith(MockitoExtension.class)
class IndividualServiceTest {

    @Mock
    private IndividualMapper individualMapper;
    @Mock
    private PairingMapper pairingMapper;
    @Mock
    private MorphMasterMapper morphMasterMapper;
    @Mock
    private BloodlineMasterMapper bloodlineMasterMapper;
    @Mock
    private IndividualMorphMapper individualMorphMapper;
    @Mock
    private IndividualBloodlineMapper individualBloodlineMapper;
    @Mock
    private IndividualImageService individualImageService;

    @InjectMocks
    private IndividualService individualService;

    @Test
    void autoGeneratedIdUsesOnlyExistingIdsForTheSelectedSpecies() {
        String speciesId = "0002";
        String idPrefix = "26A";

        MorphMasterEntity morph = new MorphMasterEntity();
        morph.setSpeciesId(speciesId);
        morph.setMorphId("001");
        morph.setMorphName("Normal");
        morph.setMorphType("SINGLE");

        when(morphMasterMapper.findByPrimaryKey(speciesId, "001")).thenReturn(morph);
        when(individualMapper.findIdsBySpeciesIdAndIdPrefix(speciesId, idPrefix)).thenReturn(List.of());
        when(individualMapper.findBySpeciesIdAndId(eq(speciesId), anyString())).thenAnswer(invocation -> {
            IndividualEntity entity = new IndividualEntity();
            entity.setSpeciesId(speciesId);
            entity.setFiscalYear(2026);
            entity.setId(invocation.getArgument(1));
            return entity;
        });
        when(individualMorphMapper.findByIndividual(eq(speciesId), anyString())).thenReturn(List.of());

        IndividualMorph visualMorph = new IndividualMorph();
        visualMorph.setMorphId("001");
        visualMorph.setExpressionCategory("0");

        Individual request = new Individual();
        request.setSpeciesId(speciesId);
        request.setFiscalYear(2026);
        request.setBreedingCategory("0");
        request.setMorphEntries(List.of(visualMorph));
        Date clientTimestamp = new Date(0);
        request.setCreateAt(clientTimestamp);
        request.setUpdateAt(clientTimestamp);

        Individual created = individualService.createIndividual(request);

        assertEquals("26A001", created.getId());
        assertEquals("system", request.getCreateUser());
        assertEquals("system", request.getUpdateUser());
        assertNotNull(request.getCreateAt());
        assertEquals(request.getCreateAt(), request.getUpdateAt());
        assertNotEquals(clientTimestamp, request.getCreateAt());
        verify(individualMapper).findIdsBySpeciesIdAndIdPrefix(speciesId, idPrefix);
    }
}
